import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const webDir = path.join(rootDir, 'packages', 'web');
const outFile = path.join(rootDir, 'packages', 'server', 'src', 'web-assets.generated.mjs');

const files = {
  '/index.html': 'index.html',
  '/styles.css': 'styles.css',
  '/app.mjs': 'app.mjs',
};

const assets = {};
for (const [route, filename] of Object.entries(files)) {
  assets[route] = await fs.readFile(path.join(webDir, filename), 'utf8');
}

const banner = `// Auto-generated by scripts/embed-web.mjs. Do not edit manually.\nexport const WEB_ASSETS = ${JSON.stringify(assets, null, 2)};\n`;
await fs.writeFile(outFile, banner, 'utf8');
console.log(`Embedded ${Object.keys(assets).length} web assets into ${path.relative(rootDir, outFile)}`);
